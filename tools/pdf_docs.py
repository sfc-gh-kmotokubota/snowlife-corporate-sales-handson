def p(text, style=BODY):
    return Paragraph(text, style)


def table(rows, widths, header=True, zebra=True):
    data = [[p(c, CELL_H if (header and i == 0) else CELL) if isinstance(c, str) else c for c in r]
            for i, r in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), NAVY))
    if zebra:
        for i in range(1 if header else 0, len(rows)):
            if i % 2 == 0:
                style.append(("BACKGROUND", (0, i), (-1, i), LIGHT))
    t.setStyle(TableStyle(style))
    return t


def kv_table(rows, widths=(32 * mm, 138 * mm)):
    data = [[p(k, CELL), p(v, CELL)] for k, v in rows]
    t = Table(data, colWidths=widths)
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("BACKGROUND", (0, 0), (0, -1), LIGHT),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def box(paras, bg=LIGHT, border=SKY):
    t = Table([[paras]], colWidths=[170 * mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), bg),
        ("BOX", (0, 0), (-1, -1), 0.8, border),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def build(path: Path, title, story, header_left, header_right="", confidential=False):
    def on_page(c, doc):
        w, h = A4
        c.saveState()
        c.setStrokeColor(NAVY)
        c.setLineWidth(1.2)
        c.line(20 * mm, h - 14 * mm, w - 20 * mm, h - 14 * mm)
        c.setFont(FONT, 8)
        c.setFillColor(NAVY)
        c.drawString(20 * mm, h - 12 * mm, header_left)
        c.drawRightString(w - 20 * mm, h - 12 * mm, header_right)
        if confidential:
            c.setFillColor(RED)
            c.setFont(FONT, 9)
            c.drawRightString(w - 20 * mm, h - 19 * mm, "社外秘")
        c.setFillColor(GRAY)
        c.setFont(FONT, 7)
        c.drawString(20 * mm, 10 * mm, DISCLAIMER)
        c.drawRightString(w - 20 * mm, 10 * mm, f"- {doc.page} -")
        c.restoreState()

    doc = SimpleDocTemplate(str(path), pagesize=A4, title=title, author="スノー生命保険株式会社（架空）",
                            leftMargin=20 * mm, rightMargin=20 * mm, topMargin=22 * mm, bottomMargin=18 * mm)
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)


