USE ROLE ACCOUNTADMIN;
USE SECONDARY ROLES NONE;
USE WAREHOUSE SNOWLIFE_HANDSON_WH;
USE SCHEMA SNOWLIFE_HANDSON_DB.RAW;

-- Q1. 進行中の商談のうち、見込みランクAの見込み金額合計を支社別に（円）
SELECT b.BR_NM, SUM(o.AMT_EST) * 1000 AS EXPECTED_PREMIUM_JPY
FROM SF_OPPORTUNITY o
JOIN SF_ACCOUNT a ON o.ACCT_ID = a.ACCT_ID
JOIN SF_BRANCH b  ON a.BR_CD = b.BR_CD
WHERE o.STAGE_CD NOT IN ('90', '99') AND o.RANK_FLG = 'A'
GROUP BY b.BR_NM ORDER BY 2 DESC;

-- Q2. 2026年度上期（2026-04-01〜2026-09-30）に受注した商談の件数と見込み金額合計（円）
SELECT COUNT(*) AS WON_CNT, SUM(AMT_EST) * 1000 AS WON_PREMIUM_JPY
FROM SF_OPPORTUNITY
WHERE STAGE_CD = '90' AND CLOSE_DT BETWEEN '2026-04-01' AND '2026-09-30';

-- Q3. 製造業の取引先の社数
SELECT COUNT(*) AS MFG_ACCOUNTS FROM SF_ACCOUNT WHERE IND_CD = 'MFG';

-- Q4. 従業員5,000人以上で、総合福祉団体定期保険の有効な既契約がない取引先
SELECT a.ACCT_NM, a.EMP_CNT
FROM SF_ACCOUNT a
WHERE a.EMP_CNT >= 5000
  AND NOT EXISTS (SELECT 1 FROM SF_CONTRACT c
                  WHERE c.ACCT_ID = a.ACCT_ID AND c.PRD_CD = 'P01' AND c.STS_CD = '1')
ORDER BY a.EMP_CNT DESC;

-- Q5. 進行中でランクS・Aの商談がある取引先のうち、2026年7〜9月に訪問（対面）していない取引先
SELECT DISTINCT a.ACCT_NM
FROM SF_OPPORTUNITY o
JOIN SF_ACCOUNT a ON o.ACCT_ID = a.ACCT_ID
WHERE o.STAGE_CD NOT IN ('90', '99') AND o.RANK_FLG IN ('S', 'A')
  AND NOT EXISTS (SELECT 1 FROM SF_ACTIVITY v
                  WHERE v.ACCT_ID = a.ACCT_ID AND v.ACT_TYP = 'V'
                    AND v.ACT_DT BETWEEN '2026-07-01' AND '2026-09-30')
ORDER BY 1;

-- Q6. 2026年度上期の支社別の訪問件数（対面の訪問のみ）
SELECT b.BR_NM, COUNT(*) AS VISIT_CNT
FROM SF_ACTIVITY v
JOIN SF_ACCOUNT a ON v.ACCT_ID = a.ACCT_ID
JOIN SF_BRANCH b  ON a.BR_CD = b.BR_CD
WHERE v.ACT_TYP = 'V' AND v.ACT_DT BETWEEN '2026-04-01' AND '2026-09-30'
GROUP BY b.BR_NM ORDER BY 2 DESC;

-- Q7. 有効な既契約の年間保険料合計の上位5社（円）
SELECT a.ACCT_NM, SUM(c.ANN_PREM) AS ACTIVE_PREMIUM_JPY
FROM SF_CONTRACT c JOIN SF_ACCOUNT a ON c.ACCT_ID = a.ACCT_ID
WHERE c.STS_CD = '1'
GROUP BY a.ACCT_NM ORDER BY 2 DESC LIMIT 5;

-- Q8. GLTD の進行中の商談の件数と見込み金額合計（円）
SELECT COUNT(*) AS GLTD_OPEN_CNT, SUM(AMT_EST) * 1000 AS GLTD_OPEN_PREMIUM_JPY
FROM SF_OPPORTUNITY
WHERE PRD_CD = 'P02' AND STAGE_CD NOT IN ('90', '99');

-- Q9. 2025年度の売上高が2024年度より増えていて、進行中の商談がある取引先
SELECT a.ACCT_NM, f25.REVENUE_MJPY AS REV_2025, f24.REVENUE_MJPY AS REV_2024
FROM SF_ACCOUNT a
JOIN SNOWLIFE_HANDSON_DB.MART.V_COMPANY_FINANCIALS f25 ON f25.ACCT_ID = a.ACCT_ID AND f25.FISCAL_YEAR = 2025
JOIN SNOWLIFE_HANDSON_DB.MART.V_COMPANY_FINANCIALS f24 ON f24.ACCT_ID = a.ACCT_ID AND f24.FISCAL_YEAR = 2024
WHERE f25.REVENUE_MJPY > f24.REVENUE_MJPY
  AND EXISTS (SELECT 1 FROM SF_OPPORTUNITY o WHERE o.ACCT_ID = a.ACCT_ID AND o.STAGE_CD NOT IN ('90', '99'))
ORDER BY 1;

-- Q10. 2026年7〜9月の求人件数合計が、前年同期（2025年7〜9月）の1.5倍以上の取引先
SELECT a.ACCT_NM,
       SUM(IFF(j.POST_MONTH BETWEEN '2026-07-01' AND '2026-09-01', j.POSTING_CNT, 0)) AS CNT_2026Q2,
       SUM(IFF(j.POST_MONTH BETWEEN '2025-07-01' AND '2025-09-01', j.POSTING_CNT, 0)) AS CNT_2025Q2
FROM SNOWLIFE_HANDSON_DB.MART.V_JOB_POSTINGS j JOIN SF_ACCOUNT a ON j.ACCT_ID = a.ACCT_ID
GROUP BY a.ACCT_NM
HAVING CNT_2026Q2 >= 1.5 * CNT_2025Q2
ORDER BY 1;
